const { withGradleProperties } = require("expo/config-plugins");

/**
 * Raises the Gradle daemon's JVM Metaspace/heap ceiling in the generated
 * `android/gradle.properties`.
 *
 * Why this exists: this project's Android release build (see
 * `pnpm build:android:split`/`:apk`/`:bundle`) failed with
 *
 *   Execution failed for task ':app:packageRelease'.
 *   > A failure occurred while executing ...PackageAndroidArtifact$IncrementalSplitterRunnable
 *
 * which looks like a packaging bug but is actually a symptom hidden in the
 * Gradle daemon log: "Daemon will be stopped ... after running out of JVM
 * Metaspace". This app pulls in a large number of native-module Gradle
 * plugins (reanimated, worklets, webrtc, callkeep, notifee, and more), and a
 * split-APK release build (4 ABIs, R8, lint-vital, resource
 * shrinking/optimizing, all in one long-lived daemon) loads far more classes
 * than Expo's default template's `-XX:MaxMetaspaceSize=512m` budget allows,
 * especially once the daemon has already served an earlier build in the
 * same session (Gradle daemons are reused across invocations by default).
 *
 * Why a config plugin instead of hand-editing `android/gradle.properties`
 * directly: that file is regenerated by `expo prebuild` on every run (see
 * `package.json`'s `build:android:*` scripts, which all run `expo prebuild`
 * first — see docs/architecture/versioning.md for why), so a manual edit
 * there is silently wiped out the next time any of those scripts run. A
 * `withGradleProperties` mod runs as part of prebuild itself, so it survives
 * every regeneration — the same reasoning as this project's other config
 * plugin, `withEncryptedPush.js`.
 */
const withAndroidGradleMemory = (config) => {
    return withGradleProperties(config, (mod) => {
        const jvmArgsProperty = mod.modResults.find(
            (item) => item.type === "property" && item.key === "org.gradle.jvmargs"
        );

        const jvmArgs = "-Xmx4096m -XX:MaxMetaspaceSize=1536m -XX:+HeapDumpOnOutOfMemoryError";

        if (jvmArgsProperty) {
            jvmArgsProperty.value = jvmArgs;
        } else {
            mod.modResults.push({ type: "property", key: "org.gradle.jvmargs", value: jvmArgs });
        }

        return mod;
    });
};

module.exports = withAndroidGradleMemory;
